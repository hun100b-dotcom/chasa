// ---------------------------------------------------------------------------
// 4) 철삭 3타 콤보
//    한 줄이 한 타. 숫자를 바꿔서 각 타의 성격을 바꿀 수 있다.
// ---------------------------------------------------------------------------
export interface ComboStep {
  /** 이름 (코드 읽기용) */
  name: string;
  /** 기본 데미지. 실제로는 ±DAMAGE_VARIANCE 만큼 랜덤하게 흔들린다. */
  damage: number;
  /** 사슬 길이 = 공격 반경. 이 거리 안의 적이 맞는다. */
  reach: number;
  /** 사슬이 쓸고 지나가는 각도(°). 150 = 부채꼴, 360 = 한 바퀴 회전 */
  sweepDeg: number;
  /** 정면 기준 얼마나 옆에서 휘두르기 시작하나(°). 부채꼴이면 sweep의 절반 → 정면이 정중앙 */
  startOffsetDeg: number;
  /** 휘두르는 방향. +1 = 시계 반대, -1 = 시계. 1타·2타를 반대로 해서 왕복 느낌을 낸다. */
  dir: 1 | -1;
  /** 준비 동작(선딜) 시간. 길수록 묵직하지만 답답하다. */
  windup: number;
  /** 실제로 휘두르는 시간. 짧을수록 빠르고 날카롭다. */
  swing: number;
  /** 휘두른 뒤 굳는 시간(후딜). 이 구간에 클릭해두면 다음 타가 이어진다. */
  recover: number;
  /** 히트스톱: 맞는 순간 게임이 멈추는 프레임 수 (요청: 2~4프레임) */
  hitStopFrames: number;
  /** 화면 흔들림 세기 (0~1). 1이 최대. 세기에 비례해서 흔들린다. */
  shake: number;
  /** 넉백 초기 속도. 클수록 멀리 날아간다. (날아가는 거리 ≈ 속도 / ENEMY.KNOCKBACK_FRICTION) */
  knockback: number;
  /** 맞은 적이 멍해서 못 움직이는 시간 */
  stun: number;
  /** 휘두르는 동안 앞으로 살짝 미끄러져 들어가는 거리 (추진력 = 손맛) */
  lunge: number;
}


def soul(i, how='고른다'):
    s = db[i]
    return {'id': i, 'name': s['name'], 'age': s['type'], 'seal': s['seal'], 'memory': s['memory'], 'fact': s['fact'], 'choice': how}

def beat(at, phase, scene, do, learn, souls=None, lines=None, refs=None, note=None):
    b = {'at': at, 'phase': phase, 'scene': scene, 'player': do, 'learn': learn}
    if souls: b['souls'] = souls
    if lines: b['lines'] = lines
    if refs: b['refs'] = refs
    if note: b['note'] = note
    return b

def L(speaker, text, kind='bubble'):
    return {'speaker': speaker, 'text': text, 'style': kind}


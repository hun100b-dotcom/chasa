def build():
    out = []
    for b in BOSSES:
        r = RING[b["id"]]
        mult = 1 + RING_STEP * (r - 1)
        d = dict(b)
        d["ring"] = r
        d["maedhim"] = boss_hp(b["id"])
        d["neok_tendo"] = 0 if b["id"] in ("B-14", "B-20") else int(round(COMMON_S1["neok_tendo_base"] * mult / (1 + RING_STEP)))
        d["clues"] = [dict(verb=v, text=t) for v, t in b["clues"]]
        out.append(d)
    bad = [(b["id"], p["name"]) for b in out for ph in b["phases"] for p in ph["patterns"] if p["windup"] > 0 and not p["ok"]]
    return dict(_설명="tools/boss_s2.py가 만든 파일. 직접 고치지 말고 생성기를 고친다.",
                common=dict(COMMON_S1, dam_tick_boss_pahon=10, release_ratio_min=0.6, b20_hp_per_size=2, b20_hp_cap=3200),
                windup_fail=bad, bosses=out)



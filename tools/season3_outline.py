def C(cid, verb, zone, place, what, points_to, line=None, half=None, text=None, soul=None, alt=None, time='낮', note=None, speaker=None):
    """단서 하나(시즌 1·2와 같은 모양). 시즌 3의 '낮'은 ①~⑥ 위층(산 사람이 있는 곳), ⑦~⑩은 새벽 틈."""
    c = {'id': cid, 'verb': verb, 'time': time, 'zone': zone, 'place': place, 'what': what, 'points_to': points_to}
    if line: c['line'], c['line_half'] = line, half
    if speaker: c['speaker'] = speaker   # 말하는 이(시즌 3 npc 표가 나오면 N-번호로 바꾼다)
    if text: c['text'] = text
    if soul:
        assert soul in MEM, soul
        c['soul'] = soul
        c['memory'] = MEM[soul]['memory']
    if alt: c['alt'] = alt
    if note: c['note'] = note
    return c


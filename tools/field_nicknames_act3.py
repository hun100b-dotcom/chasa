    for x, z, zone, place, nick, spot, lines, kind in CAMPS:
        for n in nick:
            if n in seen or n in TAKEN: bad.append('별명 겹침 ' + n)
            seen.add(n)
        for i, (sp, ln) in enumerate(lines):
            if len(sp) > 10 or len(ln) > 40: bad.append('길이 ' + ln)
            if nick[i] not in ln: bad.append('별명이 말에 없음 ' + ln)
            for w in BAN:
                if w in ln or w in sp: bad.append(f"금지어 '{w}': {ln}")
            for c in ln:
                try: c.encode('euc-kr')
                except UnicodeEncodeError: bad.append('글꼴 밖 ' + c)
    return bad


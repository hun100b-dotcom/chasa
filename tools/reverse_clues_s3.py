def gives(b):
    if b['region'] == 4:
        return '이름(시즌 1 B-08 천도) 또는 목패 번호(반쪽 — 이튿날 목패에 번호가 새겨진다)'
    if b['region'] == 6:
        return '이름 또는 별명(별명도 이름이다, B-11 규칙)'
    return '이름'


mem = json.load(open(MEM, encoding='utf-8'))
rows = []
for b in mem['baek']:
    sid, r, z = b['id'], b['region'], b['zone']
    base = {'baek': sid, 'name': b['name'], 'region': r, 'zone': z}
    if sid in NONE:
        rows.append(dict(base, clue_id=None, note=NONE[sid])); continue
    cid = sid.replace('S-', 'S') + '-R'
    need = '짝 혼을 시즌 1 · 2에서 천도하지 않았을 때(파혼 = 주인 없는 백 / 미처결 / 짝 없음) 이 단서로 이름을 얻는다. 천도했으면 이미 안다(보기만 가능)' if b['link'] else \
           '짝이 없는 백 — 이름은 이 단서에서만 얻는다. 못 찾고 눕히면 반쪽'
    if r >= 7:
        row = dict(base, clue_id=cid, cut='LEDGER-REVERSE', time='새벽 틈' if r != 7 else '새벽 틈(⑦ 나루, 새벽 2분 + 낮 처음 6분)',
                   fill={'line_row': f'{LEDGER[r]} — {ROW[sid]}'}, gives=gives(b), needed=need)
        if r == 9:
            row['note'] = '시즌 2 B-18을 천도하지 않아 ⑨에 새벽이 없으면 같은 줄을 "먹지기의 흔적"(언제나)으로 본다(world.day_clues)'
    else:
        if sid in SIX:
            middle, empty = SIX[sid]
        elif sid in GROUP7:
            middle, empty = GROUP7[sid]
        else:  # 7막 이름 새기기 — 빈 것은 장례 대본의 첫 "멈춘 것"과 같은 자리
            middle, empty = CARVE_MIDDLE[sid], CARVE[sid][0]
        row = dict(base, clue_id=cid, cut='RITE-REVERSE', time='낮(그 백의 아래층에 처음 내려간 다음 낮)',
                   fill={'last': LAST[z], 'middle': middle, 'empty': empty}, gives=gives(b), needed=need)

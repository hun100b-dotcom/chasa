def build():
    out = []
    for b in BOSSES:
        r = RING[b["id"]]
        mult = 1 + RING_STEP * (r - 1)
        d = dict(b)
        d["ring"] = r
        d["maedhim"] = boss_hp(b["id"])
        d["neok_tendo"] = 0 if b["id"] in NO_NEOK else int(round(COMMON_S1["neok_tendo_base"] * mult / (1 + RING_STEP)))
        d["clues"] = [dict(verb=v, text=t) for v, t in b["clues"]]
        out.append(d)
    bad = [(b["id"], p["name"]) for b in out for ph in b["phases"] for p in ph["patterns"] if p["windup"] > 0 and not p["ok"]]
    return dict(_설명="tools/boss_s3.py가 만든 파일. 직접 고치지 말고 생성기를 고친다.",
                common=dict(COMMON_S1, verbs=["눕히기", "깨뜨리기"], b23_release=[20, 300], ending_a=[150, 60],
                            kneel_wait={"default": 7, "B-27": 10, "B-31": 15}),
                windup_fail=bad, bosses=out)



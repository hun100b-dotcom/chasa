# 유형: 천도 수 T, 파혼 수(일반) p, 보스 파혼 수 b (업 +3), 눕히기 수 L(6~8막), 이름 쪽지 등 기억 보너스 m
ARCH = {
 "천도 위주":       dict(T=800, p=80,  b=0, L=30, m=30),
 "균형":             dict(T=500, p=300, b=2, L=22, m=20),
 "파혼 위주(성실)": dict(T=200, p=600, b=4, L=20, m=30),
 "파혼 위주(방치)": dict(T=200, p=600, b=8, L=7,  m=0),
 "시즌3 시작(기본)": dict(T=120, p=50,  b=0, L=27, m=0),   # 기본 상태: 천도 120, 파혼 50
}
def karma(a, D): return max(0.0, a['p'] + 3*a['b'] - D*a['T'])
print("[결말 A 조건] 기억 200 이상 + 업 60 미만. 기억 = 천도 수 + 눕히기 + 보너스, 업 = 파혼 + 3×보스파혼 − 감쇠×천도")
for D in (0.0, 0.25, 0.5, 1.0):
    print(f"\n 천도당 업 감소 D={D}")
    for k, a in ARCH.items():
        mem = a['T'] + a['L'] + a['m']; kr = karma(a, D)
        print(f"   {k:<16} 기억 {mem:4d}  업 {kr:6.1f}  → {'눕히기 가능(A)' if mem>=200 and kr<60 else ('기억 부족' if mem<200 else '업 초과(C)')}")
print("\n[B-31 일곱의 빛] 보낸 사람 수 / N (최소 1, 최대 7), 하나당 밀침 -12%")
for N in (1, 40):
    print(f" N={N}: " + ", ".join(f"{k}={min(7, max(1, (a['T']+a['L'])//N))}개(밀침 -{min(7, max(1,(a['T']+a['L'])//N))*12}%)" for k, a in ARCH.items()))
print("\n[캐스팅 하한] 일반 1.5초 − 알고 있음 0.5 − B-29 남은 백 0.5 = 0.5초 (CAST_MIN_TIME). 더 줄지 않음")
print("[이동 둔화 합산] 먹 앙금 -15% + 둔화 웅덩이 -20% + 안개 -20% 이면 곱연산 약 -50%. 상한 -35% 권고")
print(f" 곱연산: {(1-.15)*(1-.20)*(1-.20)*100:.0f}% 속도")

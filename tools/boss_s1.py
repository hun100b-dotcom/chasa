def need_windup(dist_m):
    """이 거리만큼 비켜서야 피할 수 있는 공격에 필요한 최소 예고 시간(초).
    = 반응 시간 + 걸어서 비키는 시간 + 터치 여유. 소수 둘째 자리에서 올림."""
    import math
    return math.ceil((REACTION + dist_m / MOVE_SPEED + MARGIN) * 100) / 100


def boss_hp(bid):
    """보스 맺힘 = 800 × (그 고리의 보상 배율 ÷ B-01 고리의 보상 배율).
    보상이 +25%씩 크는 만큼 버티는 힘도 같이 크게 해서, 바깥 보스가 '더 멀고 더 단단하다'를 맞춘다."""
    r = RING[bid]
    hp = BOSS_BASE_HP * (1 + RING_STEP * (r - 1)) / (1 + RING_STEP * (2 - 1))
    if bid == "B-12":
        hp *= FINALE_MULT
    return int(round(hp / 10.0) * 10)


# 패턴 하나 = 이름, 모양, 예고 시간(초), 비켜야 하는 거리(m), 맞으면, 출처
def P(name, shape, windup, dodge_m, hit, src="제안"):
    return dict(name=name, shape=shape, windup=windup, dodge_m=dodge_m, need=need_windup(dodge_m),
                ok=windup >= need_windup(dodge_m), hit=hit, source=src)



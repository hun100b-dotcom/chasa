def render(data, title, intro, sec, common_rows, asks, verbs=("천도", "파혼")):
    """보스 부록 마크다운을 만든다. 시즌 1·2·3 생성기가 같은 모양으로 쓰도록 함께 쓴다.
    sec: 소제목 번호 앞머리(예: "E1" → E1-1, E1-2 …)
    verbs: 두 선택의 이름. 시즌 3는 몸(백)이 상대라 ("눕히기", "깨뜨리기")를 쓴다"""
    good, bad = verbs
    L = []
    A = L.append
    A("## " + title)
    A("")
    A(intro)
    A("")
    A("### %s-1. 모든 보스에 같은 규칙" % sec)
    A("")
    A("| 항목 | 값 | 왜 |")
    A("|---|---|---|")
    for k, v, w in common_rows:
        A("| %s | %s | %s |" % (k, v, w))
    A("")
    fails = data["windup_fail"]
    A("예고 하한 점검: 패턴 %d개 중 하한에 못 미치는 것 **%d개**%s." % (
        sum(1 for b in data["bosses"] for ph in b["phases"] for p in ph["patterns"] if p["windup"] > 0),
        len(fails), "" if not fails else " (" + ", ".join("%s %s" % f for f in fails) + ")"))
    A("")
    A("### %s-2. 한눈에" % sec)
    A("")
    A("| 보스 | 원형 · 장소 | 맺힘 | 목표 시간 | 약점 한 줄 | %s하면 | %s하면 |" % (good, bad))
    A("|---|---|---|---|---|---|---|")
    for b in data["bosses"]:
        A("| %s %s | %s · %s | %d | %s | %s | %s | %s |" % (
            b["id"], b["name"], b["archetype"], b["place"], b["maedhim"], b["minutes"],
            b["weak"]["what"].split(". ")[0], b["tendo"], b["pahon"]))
    A("")
    A("### %s-3. 보스별 사양" % sec)
    for b in data["bosses"]:
        A("")
        A("#### %s %s — %s" % (b["id"], b["name"], b["place"]))
        A("")
        A("한: %s. 원형 %s, 맺힘 %d, 목표 %s%s." % (b["han"], b["archetype"], b["maedhim"], b["minutes"],
                                              ", %s 넋 %d" % (good, b["neok_tendo"]) if b["neok_tendo"] else ""))
        A("")
        A("| 단계 | 무대 | 패턴 | 모양 | 예고 | 맞으면 |")
        A("|---|---|---|---|---|---|")
        for ph in b["phases"]:
            if not ph["patterns"]:
                A("| %s %s | %s | — | — | — | — |" % (ph["at"], ph["title"], ph["desc"]))
                continue
            for i, p in enumerate(ph["patterns"]):
                head = "%s %s" % (ph["at"], ph["title"]) if i == 0 else ""
                desc = ph["desc"] if i == 0 else ""
                wu = "%.1f초 (하한 %.2f)" % (p["windup"], p["need"]) if p["windup"] > 0 else "—"
                A("| %s | %s | %s | %s | %s | %s |" % (head, desc, p["name"], p["shape"], wu, p["hit"]))
        A("")
        A("약점(%s): %s" % (b["weak"]["status"], b["weak"]["what"]))
        A("")
        if b["clues"]:
            A("단서: " + " / ".join("%d. %s — %s" % (i + 1, c["verb"], c["text"]) for i, c in enumerate(b["clues"])))
            A("")
        A("%s: %s. %s: %s." % (good, b["tendo"], bad, b["pahon"]))
        if b["link"]:
            A("")
            A("숨은 연결: %s." % b["link"])
    A("")
    A("### %s-4. 확인 요청" % sec)
    A("")
    A("| 누구 | 무엇 |")
    A("|---|---|")
    for who, what in asks:
        A("| %s | %s |" % (who, what))
    return "\n".join(L) + "\n"



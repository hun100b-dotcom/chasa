print("[B-23 조건] 백 36마리 중 이번 막 눕히기 수 vs 누적 천도(시즌1·2). 기준안: 서사(백 24 또는 천도 150) / 권고(백 20 또는 천도 300)")
ARCH = {  # 누적 천도, 6막에서 백을 눕히는 비율(나머지는 깨뜨림)
 "천도 위주":       (800, 0.90),
 "균형":             (500, 0.60),
 "파혼 위주(성실)": (200, 0.55),
 "파혼 위주(방치)": (200, 0.20),
 "시즌3 시작(기본 120)": (120, 0.75),
 "시즌3 시작(기본 120, 방치)": (120, 0.20),
}
def ok(T, rate, bk, tk): return "풀기" if (round(36 * rate) >= bk or T >= tk) else "끊기만"
print(f"  {'유형':<24}{'눕히기':>5}  서사안  권고안")
for k, (T, r) in ARCH.items():
    print(f"  {k:<24}{round(36*r):>5}  {ok(T,r,24,150):<6}  {ok(T,r,20,300)}")
print("\n[B-22] 일곱 동시 무릎: 한 마리 맺힘 깎기 약 2.5초, 3타 회전은 평균 2.5마리 동시 타격 가정")
for win in (10, 15):
    sequential = 7 * 2.5
    aoe = sequential / 2.5
    print(f"  창 {win}s: 단일 타격만이면 {sequential:.1f}s(불가능), 범위 타격 활용 시 약 {aoe:.1f}s + 이동 4s = {aoe+4:.1f}s → {'가능' if aoe+4<=win else '빠듯'}")
print("\n[B-22 보상] 선원의 밧줄 사거리 +1.5m: 3타 5.6m 기준")
for add in (1.5, 0.8):
    print(f"  +{add}m: 반경 +{add/5.6*100:.0f}%, 타격 면적 +{((5.6+add)**2/5.6**2-1)*100:.0f}%")
